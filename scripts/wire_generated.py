"""Add generated problem sets to the week files, from each generator module's WEEKS map.

    python -I scripts/wire_generated.py          # show what would change
    python -I scripts/wire_generated.py --write  # write the week files

Each generator module defines WEEKS = {generator_name: term_week}. For every
course week that has generators, this puts one problem set
"gen-<course>-wNN" (generated, 4 seeds per generator) at the end of
content/<course>/weekNN.json, replacing an earlier version of that set.
ECE 201 week 1 keeps its hand-made set "gen-ece201-w1-power".
"""
import importlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

MODULE_COURSE = {"circuits_dc": "ece201", "circuits_transient": "ece201",
                 "dsp": "ece200", "vectorcalc": "mth254"}
SEEDS = [1, 2, 3, 4]
TITLES = {"ece201": "Circuit drills", "ece200": "Signal drills", "mth254": "Calculus drills"}


def plan() -> dict[tuple[str, int], list[str]]:
    by_week: dict[tuple[str, int], list[str]] = {}
    for module, course in MODULE_COURSE.items():
        mod = importlib.import_module(f"app.generators.{module}")
        for name, week in getattr(mod, "WEEKS", {}).items():
            if name not in mod.GENERATORS:
                raise SystemExit(f"{module}.WEEKS names {name!r}, which isn't in its GENERATORS")
            weeks = week if isinstance(week, (list, tuple)) else [week]
            for w in weeks:
                by_week.setdefault((course, int(w)), []).append(name)
    return by_week


def main(write: bool) -> None:
    for (course, week), names in sorted(plan().items()):
        path = ROOT / "content" / course / f"week{week:02d}.json"
        if not path.exists():
            print(f"skip {path.relative_to(ROOT)}: no week file yet ({', '.join(names)})")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        set_id = f"gen-{course}-w{week:02d}"
        data["problem_sets"] = [ps for ps in data.get("problem_sets", []) if ps.get("id") != set_id]
        data["problem_sets"].append({
            "id": set_id,
            "title": f"{TITLES[course]} (generated, new numbers each time)",
            "source": "Generated by Homebase; each answer is computed and checked a second way by code",
            "kind": "generated",
            "generated": [{"generator": n, "seeds": SEEDS} for n in names],
        })
        print(f"{path.relative_to(ROOT)}: {set_id} with {', '.join(names)}")
        if write:
            path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main("--write" in sys.argv)
